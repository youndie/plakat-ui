#!/usr/bin/env node
// B-03: the generator's goldens, emitted by the vendored design itself (research D4).
//
//   node scripts/gen-goldens.mjs [--check]
//
// Loads reference/design-system/plakat-gen.js untouched and writes a Kotlin source of goldens into
// plakat-core's common tests, so the same test holds the port on the JVM, Kotlin/Native and wasm
// (H2). A source rather than a resource file because common tests have no portable way to read a
// file on iOS and in the browser.
//
// Every composition is written in one canonical text — elements, the red element, the title zone,
// then each shape with its coordinates as integers of thousandths of a dp — so that neither side's
// float printing takes part. Most seeds are kept as a 64-bit FNV-1a hash of that text; the first
// ones of each frame and the vendored rapports are kept whole, so a failure can show what moved.
//
// --check writes nothing and fails when the committed file differs from what the design emits.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const ROOT = resolve(import.meta.dirname, '..');
const GEN = join(ROOT, 'reference/design-system/plakat-gen.js');
const OUT = join(ROOT, 'plakat-core/src/commonTest/kotlin/io/github/youndie/plakat/agit/GenGoldens.kt');

const G = await import(pathToFileURL(GEN).href);

// The frames the design uses: an empty state, the Круг poster, the vertical splash, the onboarding
// panel with its fixed title corner (Демо page), and the card thumbnail with no title (Демо page).
export const FRAMES = [
  { name: 'emptyState', W: 360, H: 240 },
  { name: 'circlePoster', W: 392, H: 392 },
  { name: 'splash', W: 240, H: 400 },
  { name: 'panel', W: 358, H: 360, head: { x: 0, y: 0, w: 72, h: 40 } },
  { name: 'thumbnail', W: 64, H: 64, head: false },
];
const SEEDS = 2000;
const WHOLE = 12;
const RAPPORTS = [1923, 1925, 1927, 1929];
const RAPPORT_SEEDS = 400;

const q = v => String(Math.round(v * 1000));
const role = f => ({ red: 'R', ink: 'I', concrete: 'C' })[f];
function shape(s) {
  if (s.k === 'rect') return `R${[s.x, s.y, s.w, s.h].map(q).join(',')},${role(s.f)}${s.rot ? ',' + [s.rot, s.ox, s.oy].map(q).join(',') : ''}`;
  if (s.k === 'circle') return `C${[s.cx, s.cy, s.r].map(q).join(',')},${role(s.f)}`;
  return `P${s.pts.map(p => p.map(q).join(',')).join(' ')},${role(s.f)}`;
}
const composition = c =>
  `${c.elements.join(',')}|${c.red ?? '-'}|${c.head ? [c.head.x, c.head.y, c.head.w, c.head.h].map(q).join(',') : '-'}|${c.shapes.map(shape).join(';')}`;
const tile = t => `${q(t.w)}x${q(t.h)}|${t.shapes.map(shape).join(';')}`;

function fnv(text) {
  let h = 0xcbf29ce484222325n;
  for (const b of Buffer.from(text, 'utf8')) {
    h ^= BigInt(b);
    h = (h * 0x100000001b3n) & 0xffffffffffffffffn;
  }
  return h.toString(16).padStart(16, '0');
}

// A Kotlin string literal, cut into pieces joined with `+` so no line passes the style's 120 columns.
const esc = s => s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\$/g, '\\$');
const kstr = (s, indent = 16) => {
  const pieces = [];
  for (let i = 0; i < s.length; i += 90) pieces.push('"' + esc(s.slice(i, i + 90)) + '"');
  if (pieces.length <= 1) return pieces[0] ?? '""';
  return pieces.join(' +\n' + ' '.repeat(indent));
};
const lines = [];
lines.push('package io.github.youndie.plakat.agit', '');
lines.push('// GENERATED by scripts/gen-goldens.mjs from reference/design-system/plakat-gen.js. Do not edit.');
lines.push('// The canonical text and the hash are defined in that script and in GenCanonical.kt.', '');
lines.push('internal object GenGoldens {');
lines.push(`    const val SEEDS: Int = ${SEEDS}`);
lines.push(`    const val RAPPORT_SEEDS: Int = ${RAPPORT_SEEDS}`, '');
lines.push('    /** Per frame: the FNV-1a 64 of every seed 1..SEEDS, 16 hex digits each. */');
lines.push('    val hashes: Map<String, String> =');
lines.push('        mapOf(');
for (const f of FRAMES) {
  let hex = '';
  for (let seed = 1; seed <= SEEDS; seed++) hex += fnv(composition(G.generate(seed, f)));
  lines.push(`            ${kstr(f.name)} to`, `                ${kstr(hex, 16)},`);
}
lines.push('        )', '');
lines.push('    /** Per frame: the whole canonical text of seeds 1..' + WHOLE + ', to show what moved. */');
lines.push('    val whole: Map<String, List<String>> =');
lines.push('        mapOf(');
for (const f of FRAMES) {
  lines.push(`            ${kstr(f.name)} to`);
  lines.push('                listOf(');
  for (let seed = 1; seed <= WHOLE; seed++) lines.push(`                    ${kstr(composition(G.generate(seed, f)), 20)},`);
  lines.push('                ),');
}
lines.push('        )', '');
lines.push('    /** rapport(seed, 24) for seeds 1..RAPPORT_SEEDS, hashed. */');
let rh = '';
for (let seed = 1; seed <= RAPPORT_SEEDS; seed++) rh += fnv(tile(G.rapport(seed, 24)));
lines.push('    val rapportHashes: String =', `        ${kstr(rh, 8)}`, '');
lines.push('    /** The vendored rapports (agit/rapport-<seed>.svg is rapport(seed, 24)), whole, at cells 12 and 24. */');
lines.push('    val rapports: Map<Pair<Int, Int>, String> =');
lines.push('        mapOf(');
for (const seed of RAPPORTS) for (const cell of [12, 24]) lines.push(`            (${seed} to ${cell}) to`, `                ${kstr(tile(G.rapport(seed, cell)), 16)},`);
lines.push('        )');
lines.push('}', '');

const text = lines.join('\n');
if (process.argv.includes('--check')) {
  let current = '';
  try { current = readFileSync(OUT, 'utf8'); } catch {}
  if (current !== text) {
    console.error(`${OUT} is stale against ${GEN}: run node scripts/gen-goldens.mjs`);
    process.exit(1);
  }
  console.log('generator goldens are up to date');
} else {
  writeFileSync(OUT, text);
  console.log(`wrote ${OUT}`);
}
