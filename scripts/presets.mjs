#!/usr/bin/env node
// B-33: generate PlakatPreset.kt from the vendored presets, agit/presets.json and its SVGs.
//
//   node scripts/presets.mjs [--check]
//
// A preset is drawn by the theme, so a figure is written with the token it is filled with, not with
// a colour: the light and the dark file must then be the same figures in their two palettes, which
// is checked here, where a preset enters, along with the README's rule for the file: only `rect`,
// `circle` and `polygon`, a `fill` that is a token, a `rotate` of −17 and nothing else. The first rect
// is the frame's paper, which the drawing puts down by itself. --check fails when the committed file
// is not what the design says today.

import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const ROOT = resolve(import.meta.dirname, '..');
const AGIT = join(ROOT, 'reference/design-system/agit');
const OUT = join(ROOT, 'plakat-core/src/commonMain/kotlin/io/github/youndie/plakat/agit/PlakatPreset.kt');
// plakat-gen.js is an ES module without a package.json saying so; read it as a data: URL.
const gen = await import(`data:text/javascript;base64,${readFileSync(join(ROOT, 'reference/design-system/plakat-gen.js')).toString('base64')}`);

const presets = JSON.parse(readFileSync(join(AGIT, 'presets.json'), 'utf8'));
const roles = { paper: 'Paper', concrete: 'Concrete', ink: 'Ink', red: 'Red' };
const palette = (pal) => Object.fromEntries(Object.keys(roles).map((token) => [pal[token].toUpperCase(), token]));

const attrs = (text) => Object.fromEntries([...text.matchAll(/([a-z]+)="([^"]*)"/g)].map((m) => [m[1], m[2]]));
const figures = (file, pal) => {
  const body = readFileSync(join(ROOT, 'reference/design-system', file), 'utf8').replace(/<metadata>.*<\/metadata>/s, '');
  const tokens = palette(pal);
  const shapes = [...body.matchAll(/<(\w+)((?:\s[^>]*)?)>/g)].filter((m) => m[1] !== 'svg').map((m) => {
    if (!['rect', 'circle', 'polygon'].includes(m[1])) throw new Error(`${file}: <${m[1]}>`);
    const a = attrs(m[2]);
    const token = tokens[a.fill?.toUpperCase()];
    if (!token) throw new Error(`${file}: fill ${a.fill} is no token`);
    const known = ['x', 'y', 'width', 'height', 'cx', 'cy', 'r', 'points', 'fill', 'transform'];
    for (const key of Object.keys(a)) if (!known.includes(key)) throw new Error(`${file}: ${key}`);
    return { kind: m[1], token, ...a, fill: undefined };
  });
  const frame = shapes.shift();
  if (frame?.kind !== 'rect' || frame.token !== 'paper' || frame.x || frame.y) throw new Error(`${file}: the first figure is not the paper`);
  return shapes;
};

const num = (v) => {
  const n = Number(v ?? 0);
  return Number.isInteger(n) ? `${n}.0` : `${n}`;
};
const role = (s) => `PlakatRole.${roles[s.token]}`;
const kotlin = (s) => {
  if (s.kind === 'circle') return `PlakatShape.Circle(${num(s.cx)}, ${num(s.cy)}, ${num(s.r)}, ${role(s)}),`;
  if (s.kind === 'polygon') {
    const points = s.points.trim().split(/\s+/).map((p) => p.split(',').map(num).join(' to '));
    return `PlakatShape.Poly(listOf(${points.join(', ')}), ${role(s)}),`;
  }
  let turn = '';
  if (s.transform) {
    const m = /^rotate\((-17) ([\d.]+) ([\d.]+)\)$/.exec(s.transform);
    if (!m) throw new Error(`transform ${s.transform}`);
    turn = `, ${num(m[1])}, ${num(m[2])}, ${num(m[3])}`;
  }
  return `PlakatShape.Rect(${num(s.x)}, ${num(s.y)}, ${num(s.width)}, ${num(s.height)}, ${role(s)}${turn}),`;
};

const camel = (id) => id[0].toUpperCase() + id.slice(1);
const entries = presets.map((p) => {
  const light = figures(p.file, gen.PAL.light);
  const dark = figures(p.dark, gen.PAL.dark);
  if (JSON.stringify(light) !== JSON.stringify(dark)) throw new Error(`${p.id}: the light and the dark file are different figures`);
  const h = p.head;
  return `    /** ${p.ru}: ${p.use}. */
    ${camel(p.id)}(
        ${p.w}.dp,
        ${p.h}.dp,
        DpRect(${h.x}.dp, ${h.y}.dp, ${h.x + h.w}.dp, ${h.y + h.h}.dp),
        listOf(
${light.map((s) => `            ${kotlin(s)}`).join('\n')}
        ),
    ),
`;
});

const text = `// GENERATED by scripts/presets.mjs from reference/design-system/agit. Do not edit.

package io.github.youndie.plakat.agit

import androidx.compose.ui.unit.Dp
import androidx.compose.ui.unit.DpRect
import androidx.compose.ui.unit.dp

/**
 * The six hand-drawn compositions of the kit, for an empty state, a splash, onboarding or a poster's ground. Draw one
 * with [PlakatPresetImage]; a title goes in its [titleZone], which no ink or red enters.
 */
public enum class PlakatPreset(
    public val width: Dp,
    public val height: Dp,
    public val titleZone: DpRect,
    internal val shapes: List<PlakatShape>,
) {
${entries.join('\n')}}
`;

if (process.argv.includes('--check')) {
  if (readFileSync(OUT, 'utf8') !== text) {
    console.error('PlakatPreset.kt is not what the design says: run node scripts/presets.mjs');
    process.exit(1);
  }
  console.log('presets are up to date');
} else {
  writeFileSync(OUT, text);
  console.log(`wrote ${OUT}`);
}
