#!/usr/bin/env node
// B-19: the poster compositions' goldens, emitted by the Core page's own generator.
//
//   node scripts/poster-goldens.mjs [--check]
//
// The Core page does not draw its posters and card thumbnails with plakat-gen.js: its script carries a
// smaller generator of its own, `comp(seed, W, H, pal, safe, opt)` beside `rng(seed)`. This script
// cuts those two methods out of the vendored page untouched, runs them in Node, and writes a Kotlin
// source of goldens into plakat-core's common tests (a source, as gen-goldens.mjs explains), for each
// way the page calls it: the three posters and the card thumbnail.
//
// A composition is written as the page writes it — the shapes' CSS values joined, then the circle —
// with the palette as role letters (R red, I ink, G gray), so the Kotlin side only has to print the
// same strings. Seeds 1..SEEDS are hashed with FNV-1a 64; the first WHOLE are kept whole.
//
// The MVP page's rapport strip is held the same way (see `raport` below).
//
// --check writes nothing and fails when the committed file differs from what the page emits.

import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const ROOT = resolve(import.meta.dirname, '..');
const PAGE = join(ROOT, 'reference/design-system/plakat-ui Ядро.dc.html');
const OUT = join(ROOT, 'plakat-core/src/commonTest/kotlin/io/github/youndie/plakat/agit/PosterGoldens.kt');

// The page's `rng` and `comp`, from `  rng(seed)` up to `  bez(t)`, as methods of a class of their own.
const src = readFileSync(PAGE, 'utf8');
const from = src.indexOf('  rng(seed) {');
const to = src.indexOf('  bez(t) {', from);
if (from < 0 || to < 0) throw new Error(`${PAGE}: rng/comp not found`);
const Page = new Function(`return class { ${src.slice(from, to)} }`)();
const page = new Page();

const pal = (gray) => (gray ? { red: 'R', ink: 'I', gray: 'G' } : { red: 'R', ink: 'I' });
// The calls the page makes, in the same order as in PlakatPosterCompositionTest.
export const FRAMES = [
  { name: 'circle', W: 390, H: 312, gray: true, safe: [{ x: 0, y: 24, w: 290, h: 288 }], opt: { redSlot: 'circle', strict: ['circle'], photoCircle: true } },
  { name: 'background', W: 390, H: 500, gray: false, safe: [{ x: 0, y: 80, w: 300, h: 240 }], opt: {} },
  { name: 'banner', W: 176, H: 160, gray: true, safe: [], opt: { redSlot: 'circle', dot: 0.5 } },
  { name: 'thumbnail', W: 64, H: 64, gray: true, safe: [], opt: { dot: 0.4 } },
];
const SEEDS = 2000;
const WHOLE = 12;

// The MVP page's rapport strip under a top app bar, `raport(seed, cols, rows, cell, pal)` beside its own
// `rng`: not plakat-gen.js's `rapport` either (B-25). Cut out the same way.
const MVP_PAGE = join(ROOT, 'reference/design-system/plakat-ui Компоненты.dc.html');
const mvp = readFileSync(MVP_PAGE, 'utf8');
const method = (text, head) => {
  const start = text.indexOf(`  ${head}`);
  if (start < 0) throw new Error(`${head} not found in ${MVP_PAGE}`);
  const end = text.indexOf('\n  }\n', start);
  const line = text.indexOf('\n', start);
  // A method on one line ends there; a longer one at its closing brace.
  return text.slice(start, text.slice(start, line).trimEnd().endsWith('}') ? line : end + 4);
};
const Mvp = new Function(`return class { ${method(mvp, 'rng(seed)')}\n${method(mvp, 'raport(seed')} }`)();
const strip = new Mvp();
const canonicalStrip = (cells) => cells.map((c) => [c.x, c.y, c.w, c.h, c.c, c.r, c.clip].join(',')).join(';');
const runStrip = (seed) => canonicalStrip(strip.raport(seed, 33, 2, 12, { red: 'R', alts: ['I', 'C'] }));

const canonical = (c) =>
  c.shapes.map((s) => [s.x, s.y, s.w, s.h, s.c, s.r, s.clip, s.t, s.o].join(',')).join(';') +
  `|${c.circle.x},${c.circle.y},${c.circle.d}`;
const run = (f, seed) => canonical(page.comp(seed, f.W, f.H, pal(f.gray), f.safe, f.opt));

function fnv(text) {
  let h = 0xcbf29ce484222325n;
  for (const b of Buffer.from(text, 'utf8')) {
    h ^= BigInt(b);
    h = (h * 0x100000001b3n) & 0xffffffffffffffffn;
  }
  return h.toString(16).padStart(16, '0');
}

const esc = (s) => s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\$/g, '\\$');
const kstr = (s, indent = 16) => {
  const pieces = [];
  for (let i = 0; i < s.length; i += 90) pieces.push('"' + esc(s.slice(i, i + 90)) + '"');
  if (pieces.length <= 1) return pieces[0] ?? '""';
  return pieces.join(' +\n' + ' '.repeat(indent));
};
const lines = [];
lines.push('package io.github.youndie.plakat.agit', '');
lines.push('// GENERATED by scripts/poster-goldens.mjs from the Core page\'s own generator. Do not edit.');
lines.push('// The canonical text is defined in that script and in PlakatPosterCompositionTest.', '');
lines.push('internal object PosterGoldens {');
lines.push(`    const val SEEDS: Int = ${SEEDS}`, '');
lines.push('    /** Per frame: the FNV-1a 64 of every seed 1..SEEDS, 16 hex digits each. */');
lines.push('    val hashes: Map<String, String> =');
lines.push('        mapOf(');
for (const f of FRAMES) {
  let hex = '';
  for (let seed = 1; seed <= SEEDS; seed++) hex += fnv(run(f, seed));
  lines.push(`            ${kstr(f.name)} to`, `                ${kstr(hex, 16)},`);
}
lines.push('        )', '');
lines.push(`    /** Per frame: the whole canonical text of seeds 1..${WHOLE}, to show what moved. */`);
lines.push('    val whole: Map<String, List<String>> =');
lines.push('        mapOf(');
for (const f of FRAMES) {
  lines.push(`            ${kstr(f.name)} to`);
  lines.push('                listOf(');
  for (let seed = 1; seed <= WHOLE; seed++) lines.push(`                    ${kstr(run(f, seed), 24)},`);
  lines.push('                ),');
}
lines.push('        )', '');
lines.push('    /** The strip, `raport(seed, 33, 2, 12, …)`: every seed 1..SEEDS hashed, and the first ones whole. */');
let sh = '';
for (let seed = 1; seed <= SEEDS; seed++) sh += fnv(runStrip(seed));
lines.push('    val stripHashes: String =', `        ${kstr(sh, 12)}`, '');
lines.push('    val stripWhole: List<String> =');
lines.push('        listOf(');
for (let seed = 1; seed <= WHOLE; seed++) lines.push(`            ${kstr(runStrip(seed), 16)},`);
lines.push('        )');
lines.push('}', '');

const text = lines.join('\n');
if (process.argv.includes('--check')) {
  let current = '';
  try { current = readFileSync(OUT, 'utf8'); } catch {}
  if (current !== text) {
    console.error(`${OUT} is stale against the Core page: run node scripts/poster-goldens.mjs`);
    process.exit(1);
  }
  console.log('poster goldens are up to date');
} else {
  writeFileSync(OUT, text);
  console.log(`wrote ${OUT}`);
}
