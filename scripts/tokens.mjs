#!/usr/bin/env node
// B-08: generate the kit's tokens from the design's machine-readable source (research D8).
//
//   node scripts/tokens.mjs [--check]
//
// Reads reference/design-system/plakat-tokens.json and writes one committed Kotlin file, so a token
// change in the design reads as a Kotlin diff beside it. --check writes nothing and fails when the
// committed file differs. The file is written in the layout ktlint keeps, so formatting never moves it.
// Units: 1 CSS px = 1 dp, a font size in px is the same number of sp (cmp-ui-library's rule, and what
// the pages render at device scale 1).

import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const ROOT = resolve(import.meta.dirname, '..');
const SRC = join(ROOT, 'reference/design-system/plakat-tokens.json');
const OUT = join(ROOT, 'plakat-core/src/commonMain/kotlin/io/github/youndie/plakat/tokens/PlakatTokens.kt');
const T = JSON.parse(readFileSync(SRC, 'utf8'));

const camel = (s) => s.replace(/[-/](.)/g, (_, c) => c.toUpperCase());
const pascal = (s) => camel(s).replace(/^./, (c) => c.toUpperCase());
const num = (v) => (Number.isInteger(v) ? `${v}` : `${v}`);
const f = (v) => `${num(v)}f`;
const color = (hex) => `Color(0xFF${hex.slice(1).toUpperCase()})`;

const COLORS = Object.keys(T['plakat/color']);
const L = [];
L.push('// GENERATED by scripts/tokens.mjs from reference/design-system/plakat-tokens.json. Do not edit.');
L.push(`// Design tokens ${T.$meta.kit} ${T.$meta.version} (direction ${T.$meta.direction}, ${T.$meta.date}).`);
L.push('');
L.push('package io.github.youndie.plakat.tokens');
L.push('');
L.push('import androidx.compose.animation.core.CubicBezierEasing');
L.push('import androidx.compose.animation.core.Easing');
L.push('import androidx.compose.animation.core.LinearEasing');
L.push('import androidx.compose.runtime.Immutable');
L.push('import androidx.compose.ui.graphics.Color');
L.push('import androidx.compose.ui.unit.Dp');
L.push('import androidx.compose.ui.unit.dp');
L.push('');

// ── colour ──
L.push('/**');
L.push(' * The five inks and two papers of one theme (`plakat/color`). [red], [ocher] and [slate] are the same');
L.push(' * in both themes: the dark theme prints on charcoal board, it does not invert.');
L.push(' */');
L.push('@Immutable');
L.push('public class PlakatColors(');
for (const k of COLORS) L.push(`    public val ${camel(k)}: Color,`);
L.push(') {');
for (const [role, v] of Object.entries(T['plakat/semantic'])) {
  L.push(`    /** \`plakat/semantic/${role}\`: ${v.form}. */`);
  L.push(`    public val ${camel(role)}: Color get() = ${camel(v.fill)}`);
  L.push('');
}
L.pop();
L.push('}');
L.push('');
L.push('/** The two themes: «Бумага» and «Чёрная бумага». */');
L.push('public object PlakatPalettes {');
for (const [name, key] of [['Paper', 'light'], ['BlackPaper', 'dark']]) {
  L.push(`    public val ${name}: PlakatColors =`);
  L.push('        PlakatColors(');
  for (const k of COLORS) L.push(`            ${camel(k)} = ${color(T['plakat/color'][k][key])},`);
  L.push('        )');
  if (name === 'Paper') L.push('');
}
L.push('}');
L.push('');

// ── type ──
const type = T['plakat/type'];
L.push('/** Which of the two families a type role is set in. */');
L.push('public enum class PlakatFamily { Display, Body }');
L.push('');
L.push('/**');
L.push(' * One role of the type scale (`plakat/type`): [size] in sp, [lineHeight] as a multiple of it, [weight],');
L.push(' * [tracking] in em, and whether the role is set in capitals.');
L.push(' */');
L.push('@Immutable');
L.push('public class PlakatTypeRole(');
L.push('    public val family: PlakatFamily,');
L.push('    public val size: Float,');
L.push('    public val lineHeight: Float,');
L.push('    public val weight: Int,');
L.push('    public val tracking: Float,');
L.push('    public val upperCase: Boolean,');
L.push(')');
L.push('');
L.push(`/** The type scale. Display: ${type['family/display']}; body: ${type['family/body']}. */`);
L.push('public object PlakatTypeScale {');
const roles = Object.entries(type).filter(([k]) => !k.startsWith('family/'));
roles.forEach(([k, r], i) => {
  L.push(`    public val ${pascal(k)}: PlakatTypeRole =`);
  L.push('        PlakatTypeRole(');
  L.push(`            family = PlakatFamily.${r.family === 'display' ? 'Display' : 'Body'},`);
  L.push(`            size = ${f(r.size)},`);
  L.push(`            lineHeight = ${f(r.line)},`);
  L.push(`            weight = ${r.weight ?? 400},`);
  L.push(`            tracking = ${f(r.tracking ?? 0)},`);
  L.push(`            upperCase = ${r.case === 'upper'},`);
  L.push('        )');
  if (i < roles.length - 1) L.push('');
});
L.push('}');
L.push('');

// ── line, shape, grid, size ──
const line = T['plakat/line'], shape = T['plakat/shape'], grid = T['plakat/grid'], size = T['plakat/size'];
L.push(`/** The three line weights (\`plakat/line\`), cap ${line.cap}, join ${line.join}. */`);
L.push('public object PlakatLines {');
L.push(`    public val Hair: Dp = ${num(line.hair)}.dp`);
L.push(`    public val Rule: Dp = ${num(line.rule)}.dp`);
L.push(`    public val Bar: Dp = ${num(line.bar)}.dp`);
L.push('}');
L.push('');
L.push('/** Form (`plakat/shape`): no radius, one axis, and the corner cut that lies on it. */');
L.push('public object PlakatShape {');
L.push(`    public val Radius: Dp = ${num(shape.radius)}.dp`);
L.push('');
L.push('    /** The kit\'s one diagonal, in degrees. */');
L.push(`    public const val AXIS: Float = ${f(shape.axis)}`);
L.push(`    public val CutWidth: Dp = ${num(shape.cut.w)}.dp`);
L.push(`    public val CutHeight: Dp = ${num(shape.cut.h)}.dp`);
L.push('}');
L.push('');
L.push('/** The grid (`plakat/grid`). */');
L.push('public object PlakatGrid {');
for (const [k, v] of Object.entries(grid)) L.push(`    public val ${pascal(k)}: Dp = ${num(v)}.dp`);
L.push('}');
L.push('');
L.push('/** Control sizes (`plakat/size`). */');
L.push('public object PlakatSizes {');
for (const [k, v] of Object.entries(size)) {
  if (typeof v === 'number') L.push(`    public val ${pascal(k)}: Dp = ${num(v)}.dp`);
}
L.push(`    public val SwitchWidth: Dp = ${num(size.switch.w)}.dp`);
L.push(`    public val SwitchCarriageWidth: Dp = ${num(size.switch.carriage[0])}.dp`);
L.push(`    public val SwitchCarriageHeight: Dp = ${num(size.switch.carriage[1])}.dp`);
L.push('}');
L.push('');

// ── print ──
const p = T['plakat/print'];
L.push('/** The print layers (`plakat/print`); each can be switched off, and the form under it stays flat. */');
L.push('public object PlakatPrint {');
L.push(`    /** Registration: the red layer under Display, Headline and plates, offset by [RegistrationX], [RegistrationY] (D14). */`);
L.push(`    public const val REGISTRATION_ON: Boolean = ${p.registration.enabled}`);
L.push(`    public val RegistrationX: Dp = ${num(p.registration.offset[0])}.dp`);
L.push(`    public val RegistrationY: Dp = ${num(p.registration.offset[1])}.dp`);
L.push('');
L.push(`    /** Paper texture: a ${p['paper-texture'].tile} dp tile, ${p['paper-texture'].blend}. */`);
L.push(`    public const val PAPER_TEXTURE_ON: Boolean = ${p['paper-texture'].enabled}`);
L.push(`    public val PaperTextureTile: Dp = ${num(p['paper-texture'].tile)}.dp`);
L.push(`    public const val PAPER_TEXTURE_OPACITY: Float = ${f(p['paper-texture'].opacity)}`);
L.push('');
L.push(`    /** Non-print mask over red plates: a ${p.nonprint.tile} dp tile. */`);
L.push(`    public const val NONPRINT_ON: Boolean = ${p.nonprint.enabled}`);
L.push(`    public val NonprintTile: Dp = ${num(p.nonprint.tile)}.dp`);
L.push(`    public const val NONPRINT_OPACITY: Float = ${f(p.nonprint.opacity)}`);
L.push('');
L.push(`    /** Halftone: dot pitch, screen angle in degrees, one ink. Fallback: ${p.halftone.fallback}. */`);
L.push(`    public val HalftonePitch: Dp = ${num(p.halftone.pitch)}.dp`);
L.push(`    public const val HALFTONE_ANGLE: Float = ${f(p.halftone.angle)}`);
L.push('');
L.push(`    /** Raskat: ${p.raskat.perScreen} shape a screen; its parameters' ranges as [min, max]. */`);
L.push(`    public const val RASKAT_ON: Boolean = ${p.raskat.enabled}`);
L.push(`    public const val RASKAT_PER_SCREEN: Int = ${p.raskat.perScreen}`);
for (const [k, kt] of [['angle', 'Angle'], ['t0', 'T0'], ['hard', 'Hard'], ['grainDp', 'GrainDp']]) {
  L.push(`    public val Raskat${kt}: ClosedFloatingPointRange<Float> = ${f(p.raskat[k][0])}..${f(p.raskat[k][1])}`);
}
L.push('}');
L.push('');

// ── motion ──
const d = T['plakat/motion/duration'], c = T['plakat/motion/curve'];
const bez = /cubic-bezier\(([^)]*)\)/.exec(c['hard-stop'])[1].split(',').map((x) => f(Number(x.trim())));
L.push('/** Durations in milliseconds (`plakat/motion/duration`). */');
L.push('public object PlakatDurations {');
for (const [k, v] of Object.entries(d)) L.push(`    public const val ${camel(k).replace(/([A-Z])/g, '_$1').toUpperCase()}: Int = ${v}`);
L.push('}');
L.push('');
L.push('/** Curves (`plakat/motion/curve`). No springs, no overshoot. */');
L.push('public object PlakatEasings {');
L.push('    public val Linear: Easing = LinearEasing');
L.push('');
L.push(`    /** Hard-stop, \`${c['hard-stop']}\`: a fast start and a stop with no overshoot. */`);
L.push(`    public val HardStop: Easing = CubicBezierEasing(${bez.join(', ')})`);
L.push('');
L.push('    /** Stepped, `steps(n)`: [steps] discrete frames, as CSS jumps at the end of each. */');
L.push('    public fun stepped(steps: Int): Easing = Easing { t -> if (t >= 1f) 1f else kotlin.math.floor(t * steps) / steps }');
L.push('}');
L.push('');

const text = L.join('\n');
if (process.argv.includes('--check')) {
  let current = '';
  try { current = readFileSync(OUT, 'utf8'); } catch {}
  if (current !== text) {
    console.error(`${OUT} is stale against ${SRC}: run node scripts/tokens.mjs`);
    process.exit(1);
  }
  console.log('tokens are up to date');
} else {
  writeFileSync(OUT, text);
  console.log(`wrote ${OUT}`);
}
