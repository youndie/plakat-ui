#!/usr/bin/env node
// B-32: the projection's goldens, emitted by the vendored plakat-warp.js in Node.
//
//   node scripts/warp-goldens.mjs [--check]
//
// The shapes are pure and run as they are. `warp` draws: the stubs live here. The map it is handed
// records each (u, v) it asks for and what came back, which is the grid and its positions, and the
// context it draws on records each triangle's transform, which ties the texture to the positions. The
// vendored functions run untouched.
//
// --check writes nothing and fails when the committed file differs from what the design emits. The
// numbers are compared to HOST_ULPS and not by their digits: the shapes go through Math.sin and
// Math.cos at full precision, and those differ in the last bits between arm64 and x64, so a file
// written on one fails on the other with nothing changed in the design.

import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const ROOT = resolve(import.meta.dirname, '..');
const OUT = join(ROOT, 'plakat-core/src/commonTest/kotlin/io/github/youndie/plakat/agit/WarpGoldens.kt');
const W = await import(`data:text/javascript;base64,${readFileSync(join(ROOT, 'reference/design-system/plakat-warp.js')).toString('base64')}`);

const SRC = { canvas: null, w: 1021, h: 259 };

const run = (map, o) => {
  const asked = [];
  const spy = (u, v) => {
    const p = map(u, v);
    asked.push([u, v, p]);
    return p;
  };
  const matrices = [];
  const ctx = { save() {}, restore() {}, beginPath() {}, moveTo() {}, lineTo() {}, closePath() {}, clip() {}, drawImage() {},
    transform: (...m) => matrices.push(m) };
  W.warp(ctx, SRC, spy, o);
  const us = [...new Set(asked.map((a) => a[0]))], vs = [...new Set(asked.map((a) => a[1]))];
  return { us, vs, points: asked.map((a) => a[2]), matrices };
};

const horn = W.horn({ ox: 16, oy: 312, L: 358, h0: 56, spread: 17 });
const box = W.box({ x: 16, y: 152, w: 260, h: 160, d: 96, band: [184, 288] });
const lid = W.box({ x: 16, y: 180, w: 300, h: 132, d: 96, band: [200, 300], fold: 'top', at: .2 });
const stairs = W.stairs({ x: 16, y: 312, n: 3, w: 281.5, rh: 78.3, sd: 40 });
const q = W.quadMap([10, 20], [200, 5], [220, 150], [15, 130]);

// The small grids keep the file small and ask each map all over; `whole` is a cell's own grid.
const CASES = [
  ['hornFloor', horn.map, { nu: 8, nv: 8 }],
  ['hornCeiling', W.horn({ ox: 12, oy: 8, L: 236, h0: 28, anchor: 'ceiling' }).map, { nu: 8, nv: 8 }],
  ['hornAxis', W.horn({ ox: 16, oy: 200, L: 340, h0: 40, angle: -17, anchor: 'axis' }).map, { nu: 8, nv: 8 }],
  ['hornUp', W.horn({ ox: 100, oy: 190, L: 170, h0: 20, spread: 30, angle: -90, persp: .5, pad: [.1, .2] }).map, { nu: 8, nv: 8 }],
  ['coneWhole', W.cone({ ox: 40, oy: 280, L: 320, r0: 20, r1: 92, yaw: 16, arc: 62, angle: -17, pad: [.06, 0] }).map, { nu: 8, nv: 10 }],
  ['coneShaft', W.cone({ ox: 30, oy: 100, L: 300, r0: 40, r1: 40, arc: 80 }).map, { nu: 8, nv: 10 }],
  ['columnFace', W.column({ cx: 264, r: 96, top: 112, bottom: 312, band: [168, 264], arc: 70 }).map, { nu: 8, nv: 8 }],
  ['columnBack', W.column({ cx: 130, r: 60, top: 16, bottom: 112, band: [40, 88], arc: 82, tilt: .3, spin: 4 }).map, { nu: 8, nv: 8 }],
  ['sphereBand', W.sphere({ cx: 254, cy: 210, R: 100, lon: 72, lat: 22, tilt: 14 }).map, { nu: 8, nv: 10 }],
  ['sphereEdge', W.sphere({ cx: 100, cy: 100, R: 60, lon: 86, lat: 80, tilt: 0 }).map, { nu: 16, nv: 10 }],
  ['boxSide', box.map, { nu: 4, nv: 8, folds: box.folds }],
  ['boxLid', lid.map, { nu: 4, nv: 8, vfolds: [lid.vfold] }],
  ['boxAt', W.box({ x: 16, y: 152, w: 260, h: 160, d: 96, band: [184, 288], at: .6 }).map, { nu: 4, nv: 8, folds: [.6] }],
  ['stairs0', stairs.maps[0], { nu: 4, nv: 6 }],
  ['stairs2', stairs.maps[2], { nu: 4, nv: 6 }],
  ['lineOfTwo', W.lineMap(horn.map, 1, 2), { nu: 4, nv: 8 }],
  ['quad', q, { nu: 4, nv: 6 }],
];
const WHOLE = run(box.map, { nu: 48, nv: 8, folds: box.folds });

const number = (n) => String(n);
const esc = (s) => s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\$/g, '\\$');
const kstr = (s, indent) => {
  const pieces = [];
  for (let i = 0; i < s.length; i += 80) pieces.push('"' + esc(s.slice(i, i + 80)) + '"');
  if (pieces.length <= 1) return pieces[0] ?? '""';
  return pieces.join(' +\n' + ' '.repeat(indent));
};
const encode = (r, withMatrices, at) => {
  const pad = ' '.repeat(at);
  const field = (name, value) => [`${pad}${name} =`, `${pad}    ${kstr(value, at + 8)},`];
  return [
    `${pad}tris = ${r.matrices.length},`,
    ...field('us', r.us.map(number).join(',')),
    ...field('vs', r.vs.map(number).join(',')),
    ...field('points', r.points.map((p) => (p ? p.map(number).join(',') : '-')).join(';')),
    ...field('matrices', withMatrices ? r.matrices.map((m) => m.map(number).join(',')).join(';') : ''),
  ];
};

const lines = [
  '// GENERATED by scripts/warp-goldens.mjs from plakat-warp.js. Do not edit.',
  '',
  'package io.github.youndie.plakat.agit',
  '',
  '/** A grid as `warp` asks its map for it, what came back, and the triangles it drew. `-` is an invisible point. */',
  'internal class WarpGolden(',
  '    val tris: Int,',
  '    val us: String,',
  '    val vs: String,',
  '    val points: String,',
  '    val matrices: String,',
  ')',
  '',
  'internal object WarpGoldens {',
  `    const val SOURCE_W: Int = ${SRC.w}`,
  `    const val SOURCE_H: Int = ${SRC.h}`,
  '',
  '    val cases: Map<String, WarpGolden> =',
  '        mapOf(',
];
for (const [name, map, o] of CASES) {
  lines.push(`            ${kstr(name, 16)} to`, '                WarpGolden(', ...encode(run(map, o), name === 'boxSide', 20), '                ),');
}
lines.push('        )', '', '    /** The Брус cell\'s own grid, `{ nu: 48, nv: 8, folds }`: the fold in it, and `nv` raised to 16. */');
lines.push('    val whole: WarpGolden =', '        WarpGolden(', ...encode(WHOLE, false, 12), '        )');
lines.push('}', '');

// A long enough way over the last bits of numbers of this size, and far under the 1e-9 the port is held to.
const HOST_ULPS = 1e-11;
const NUMBER = /-?\d+(?:\.\d+)?(?:e[-+]?\d+)?/g;

// The two files as text and numbers. Strings are rejoined first, as a number of another length moves their cuts.
const compare = (a, b) => {
  const flat = (s) => s.replace(/" \+\n\s*"/g, '');
  const [x, y] = [flat(a), flat(b)];
  const [nx, ny] = [x.match(NUMBER) ?? [], y.match(NUMBER) ?? []];
  if (x.replace(NUMBER, '#') !== y.replace(NUMBER, '#') || nx.length !== ny.length) return { differs: 'the text' };
  let largest = 0;
  for (let i = 0; i < nx.length; i++) {
    const d = Math.abs(Number(nx[i]) - Number(ny[i]));
    if (d > HOST_ULPS) return { differs: `number ${i}: ${nx[i]}, ${ny[i]}` };
    if (d > largest) largest = d;
  }
  return { largest };
};

const text = lines.join('\n');
if (process.argv.includes('--check')) {
  let current = '';
  try { current = readFileSync(OUT, 'utf8'); } catch {}
  const found = compare(current, text);
  if (found.differs) {
    console.error(`${OUT} is stale against plakat-warp.js, at ${found.differs}: run node scripts/warp-goldens.mjs`);
    process.exit(1);
  }
  console.log(`warp goldens are up to date (the largest difference from this host's numbers is ${found.largest})`);
} else {
  writeFileSync(OUT, text);
  console.log(`wrote ${OUT}`);
}
