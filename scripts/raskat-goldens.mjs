#!/usr/bin/env node
// B-04: raskat's goldens, emitted by the vendored design itself (research D5).
//
//   node scripts/raskat-goldens.mjs [--check]
//
// Loads reference/design-system/plakat-raskat.js untouched. Two stubs live here, never in the JS:
// `document.createElement('canvas')` gives `raskatImage` a 2D context with just `createImageData`
// and `putImageData`, so its pixels can be read; `performance.now` and `requestAnimationFrame` are a
// clock this script drives, so `roll` reports t0 at every millisecond of its run.
//
// The cases are the raskat shapes the design's pages draw, at the pages' own sizes and density.
// Each is kept as one FNV-1a 64 per pixel row of its ink map (`A`/`B` per pixel); the first case
// also keeps its field, T and M as the bits of each 32-bit float, row by row. The roll is kept as
// the bits of each double. Written as a Kotlin source in plakat-core's common tests (as
// gen-goldens.mjs does, for the same reason), in the layout ktlint keeps.

import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const ROOT = resolve(import.meta.dirname, '..');
const SRC = join(ROOT, 'reference/design-system/plakat-raskat.js');
const OUT = join(ROOT, 'plakat-core/src/commonTest/kotlin/io/github/youndie/plakat/print/RaskatGoldens.kt');

globalThis.document = {
  createElement: () => {
    const canvas = { width: 0, height: 0 };
    canvas.getContext = () => ({
      createImageData: (w, h) => ({ width: w, height: h, data: new Uint8ClampedArray(w * h * 4) }),
      putImageData: img => { canvas.image = img; },
    });
    return canvas;
  },
};
let now = 0;
let frame = null;
globalThis.performance = { now: () => now };
globalThis.requestAnimationFrame = cb => { frame = cb; return 1; };
globalThis.cancelAnimationFrame = () => { frame = null; };

const R = await import(pathToFileURL(SRC).href);
const RED = '#BE2F18', PAPER = '#EEE5D1', INK = '#1D1B18', OCHER = '#B5862F';

// size = the shape's box in CSS px; dpr = the canvas's backing scale on its page.
const CASES = [
  { name: 'tokensCircle', w: 116, h: 116, o: { a: RED, b: PAPER, angle: -17, t0: .58, hard: 12, grain: 1.5, seed: 1919, streak: .5, dpr: 2 } },
  { name: 'posterCircle', w: 120, h: 120, o: { a: RED, b: PAPER, angle: -17, t0: .58, hard: 12, grain: 2, seed: 1919, streak: .5, dpr: 2 } },
  { name: 'grain', w: 208, h: 208, o: { a: RED, b: PAPER, angle: -17, t0: .55, hard: 10, grain: 2, seed: 1919, mode: 'grain', streak: .5, dpr: 2 } },
  { name: 'dots', w: 208, h: 208, o: { a: RED, b: PAPER, angle: -17, t0: .55, hard: 10, grain: 2, seed: 1919, mode: 'dots', dpr: 2 } },
  { name: 'lines', w: 208, h: 208, o: { a: RED, b: PAPER, angle: -17, t0: .55, hard: 10, grain: 2, seed: 1919, mode: 'lines', dpr: 2 } },
  ...[1.15, .9, .7, .55].map((t0, i) => ({ name: `rollStill${i}`, w: 104, h: 104, o: { a: RED, b: PAPER, angle: -17, t0, hard: 10, grain: 1.5, seed: 1919, streak: .5, dpr: 2 } })),
  { name: 'splashWedge', w: 390, h: 390 * Math.tan(17 * Math.PI / 180), o: { a: INK, b: RED, angle: 73, t0: .5, hard: 9, grain: 2.5, seed: 1923, dpr: 2 } },
  { name: 'panelRect', w: 216, h: 232, o: { a: OCHER, b: RED, angle: -17, t0: .55, hard: 10, grain: 2, seed: 1927, dpr: 2 } },
];

function fnv(text) {
  let h = 0xcbf29ce484222325n;
  for (const b of Buffer.from(text, 'utf8')) {
    h ^= BigInt(b);
    h = (h * 0x100000001b3n) & 0xffffffffffffffffn;
  }
  return h.toString(16).padStart(16, '0');
}
const f32 = x => { const v = new DataView(new ArrayBuffer(4)); v.setFloat32(0, x); return v.getUint32(0).toString(16).padStart(8, '0'); };
const f64 = x => { const v = new DataView(new ArrayBuffer(8)); v.setFloat64(0, x); return v.getBigUint64(0).toString(16).padStart(16, '0'); };
const hex = h => [1, 3, 5].map(i => parseInt(h.slice(i, i + 2), 16));

// As drawRaskat sizes its image: the box times dpr, rounded, at least 1.
const px = c => [Math.max(1, Math.round(c.w * c.o.dpr)), Math.max(1, Math.round(c.h * c.o.dpr))];

const esc = s => s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\$/g, '\\$');
const kstr = (s, indent) => {
  const pieces = [];
  for (let i = 0; i < s.length; i += 90) pieces.push('"' + esc(s.slice(i, i + 90)) + '"');
  return pieces.length <= 1 ? (pieces[0] ?? '""') : pieces.join(' +\n' + ' '.repeat(indent));
};

const lines = ['package io.github.youndie.plakat.print', ''];
lines.push('// GENERATED by scripts/raskat-goldens.mjs from reference/design-system/plakat-raskat.js. Do not edit.', '');
lines.push('internal object RaskatGoldens {');
lines.push('    /** Per case: its pixel size and one FNV-1a 64 per row of its ink map, `A` or `B` per pixel. */');
lines.push('    val inks: Map<String, Triple<Int, Int, String>> =');
lines.push('        mapOf(');
for (const c of CASES) {
  const [w, h] = px(c);
  const img = R.raskatImage(w, h, c.o);
  const d = img.image.data, B = hex(c.o.b);
  let rows = '';
  for (let y = 0; y < h; y++) {
    let row = '';
    for (let x = 0; x < w; x++) {
      const q = (y * w + x) * 4;
      row += d[q] === B[0] && d[q + 1] === B[1] && d[q + 2] === B[2] ? 'B' : 'A';
    }
    rows += fnv(row);
  }
  lines.push(`            ${kstr(c.name, 16)} to`, `                Triple(`, `                    ${w},`, `                    ${h},`, `                    ${kstr(rows, 24)},`, '                ),');
}
lines.push('        )', '');
const first = CASES[0], [fw, fh] = px(first), field = R.raskatField(fw, fh, first.o);
let t = '', m = '';
for (let y = 0; y < fh; y++) {
  let rt = '', rm = '';
  for (let x = 0; x < fw; x++) { rt += f32(field.T[y * fw + x]); rm += f32(field.M[y * fw + x]); }
  t += fnv(rt);
  m += fnv(rm);
}
lines.push(`    /** The ${first.name} field: one FNV-1a 64 per row of the 32-bit float bits of T, then of M. */`);
lines.push('    val fieldT: String =', `        ${kstr(t, 12)}`, '');
lines.push('    val fieldM: String =', `        ${kstr(m, 12)}`, '');

// The roll to 0.58 over 320 ms, driven a millisecond at a time from 0 to 330.
const t0s = [];
now = 1000;
R.roll(v => t0s.push(v), .58, 320);
for (let ms = 0; ms <= 330 && frame; ms++) { now = 1000 + ms; const cb = frame; frame = null; cb(now); }
lines.push('    /** roll(draw, 0.58, 320): t0 at 0, 1, 2 … ms, as the bits of each double. */');
lines.push('    val roll: String =', `        ${kstr(t0s.map(f64).join(''), 12)}`);
lines.push('}', '');

const text = lines.join('\n');
if (process.argv.includes('--check')) {
  let current = '';
  try { current = readFileSync(OUT, 'utf8'); } catch {}
  if (current !== text) {
    console.error(`${OUT} is stale against ${SRC}: run node scripts/raskat-goldens.mjs`);
    process.exit(1);
  }
  console.log('raskat goldens are up to date');
} else {
  writeFileSync(OUT, text);
  console.log(`wrote ${OUT} (${t0s.length} roll frames)`);
}
