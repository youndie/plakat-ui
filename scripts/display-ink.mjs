#!/usr/bin/env node
// B-31: generate PlakatDisplayInk.kt from the bundled Rubik Mono One.
//
//   node scripts/display-ink.mjs [--check]
//
// The Stretch page fits a line by its ink (`actualBoundingBoxLeft`, `…Right`, `…Ascent` of a canvas
// measure), which common Compose cannot ask of a font: a layout knows advances, and its path for a
// range is the selection's boxes. So the font's own bounding boxes are read here, out of its `glyf`
// table, per code point. --check fails when the committed file is not what the font says today.

import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const ROOT = resolve(import.meta.dirname, '..');
const FONT = 'plakat-core/src/commonMain/composeResources/font/rubik_mono_one_regular.ttf';
const OUT = join(ROOT, 'plakat-core/src/commonMain/kotlin/io/github/youndie/plakat/theme/PlakatDisplayInk.kt');
const COLUMNS = 100;

const ttf = readFileSync(join(ROOT, FONT));
const tables = {};
for (let i = 0; i < ttf.readUInt16BE(4); i++) {
  const at = 12 + i * 16;
  tables[ttf.toString('latin1', at, at + 4)] = ttf.readUInt32BE(at + 8);
}
const unitsPerEm = ttf.readUInt16BE(tables.head + 18);
const longLoca = ttf.readInt16BE(tables.head + 50) === 1;
const metrics = ttf.readUInt16BE(tables.hhea + 34);
if (unitsPerEm !== 1000) throw new Error(`units per em: ${unitsPerEm}`);

// The Unicode BMP subtable, format 4: the kit's text is Cyrillic and Latin.
const subtables = Array.from({ length: ttf.readUInt16BE(tables.cmap + 2) }, (_, i) => tables.cmap + ttf.readUInt32BE(tables.cmap + 8 + i * 8));
const cmap = subtables.find((at) => ttf.readUInt16BE(at) === 4);
if (cmap === undefined) throw new Error('no format 4 cmap');
const segments = ttf.readUInt16BE(cmap + 6) / 2;
const glyphs = new Map();
for (let s = 0; s < segments; s++) {
  const end = ttf.readUInt16BE(cmap + 14 + s * 2);
  const start = ttf.readUInt16BE(cmap + 16 + segments * 2 + s * 2);
  const delta = ttf.readUInt16BE(cmap + 16 + segments * 4 + s * 2);
  const offsetAt = cmap + 16 + segments * 6 + s * 2;
  const offset = ttf.readUInt16BE(offsetAt);
  for (let c = start; c <= end && c !== 0xffff; c++) {
    const direct = offset === 0 ? c : ttf.readUInt16BE(offsetAt + offset + (c - start) * 2);
    if (offset !== 0 && direct === 0) continue;
    const gid = (direct + delta) & 0xffff;
    if (gid !== 0) glyphs.set(c, gid);
  }
}

const loca = (g) => (longLoca ? ttf.readUInt32BE(tables.loca + g * 4) : ttf.readUInt16BE(tables.loca + g * 2) * 2);
const advance = (g) => ttf.readUInt16BE(tables.hmtx + Math.min(g, metrics - 1) * 4);
const box = (g) => {
  if (loca(g) === loca(g + 1)) return [0, 0, 0];
  const at = tables.glyf + loca(g);
  return [ttf.readInt16BE(at + 2), ttf.readInt16BE(at + 6), ttf.readInt16BE(at + 8)];
};

const codes = [...glyphs.keys()].sort((a, b) => a - b);
const advances = new Set(codes.map((c) => advance(glyphs.get(c))));
const wide = Math.max(...advances);
if ([...advances].some((a) => a !== 0 && a !== wide)) throw new Error(`not monospaced: ${[...advances]}`);
const capHeight = box(glyphs.get(0x48))[2];

const rows = codes.map((c) => {
  const g = glyphs.get(c);
  return `${c.toString(16)},${advance(g) === 0 ? 0 : 1},${box(g).join(',')};`;
});
const lines = [];
let line = '';
for (const row of rows) {
  if (line.length + row.length > COLUMNS) {
    lines.push(line);
    line = '';
  }
  line += row;
}
if (line) lines.push(line);

const kotlin = `// GENERATED by scripts/display-ink.mjs from the bundled Rubik Mono One. Do not edit.

package io.github.youndie.plakat.theme

/**
 * Rubik Mono One's ink, in units of 1000 to the em: what a canvas measure tells the Stretch page and a Compose
 * layout does not tell ([PlakatStretch][io.github.youndie.plakat.components.PlakatStretch]).
 */
internal object PlakatDisplayInk {
    const val CAP_HEIGHT: Int = ${capHeight}
    const val ADVANCE: Int = ${wide}

    /** Per code point: the code in hex, 1 if it advances, then its left, right and top (all 0 for a blank glyph). */
    const val ROWS: String =
${lines.map((l, i) => `${i === 0 ? '        ' : '            '}"${l}"`).join(' +\n')}
}
`;

if (process.argv.includes('--check')) {
  if (readFileSync(OUT, 'utf8') !== kotlin) {
    console.error('PlakatDisplayInk.kt is not what the font says: run node scripts/display-ink.mjs');
    process.exit(1);
  }
} else {
  writeFileSync(OUT, kotlin);
}
console.log(`${codes.length} code points, cap ${capHeight}, advance ${wide}`);
