#!/usr/bin/env node
// B-33: the halftone's goldens, emitted by the vendored plakat-gen.js in Node.
//
//   node scripts/halftone-goldens.mjs [--check]
//
// `halftone(ctx, src, o)` needs a document for its offscreen canvas and a real canvas to read pixels
// from. The stubs live here: the offscreen canvas holds the design's stand-in, worked out per pixel from
// `standIn`'s own gradient (the same stops, in the page's frame) so that the Kotlin test can make the
// same one, and the context it draws on records each `arc`. The vendored function runs untouched. A
// small frame is written dot by dot, a large one as its count and sums, with some dots whole.
//
// --check writes nothing and fails when the committed file differs from what the design emits.

import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const ROOT = resolve(import.meta.dirname, '..');
const OUT = join(ROOT, 'plakat-core/src/commonTest/kotlin/io/github/youndie/plakat/agit/HalftoneGoldens.kt');
const G = await import(`data:text/javascript;base64,${readFileSync(join(ROOT, 'reference/design-system/plakat-gen.js')).toString('base64')}`);

// standIn(W, H, fx, fy): '#f2f2f2' under a radial gradient of R × .62 about (W fx, H fy).
const STOPS = [[0, 0x15], [.3, 0x20], [.55, 0x8a], [.8, 0xdc], [1, 0xf4]];
const gray = (W, H, fx, fy, x, y) => {
  const t = Math.hypot(x + .5 - W * fx, y + .5 - H * fy) / (Math.min(W, H) * .62);
  if (t >= 1) return STOPS[4][1];
  let i = 0;
  while (t > STOPS[i + 1][0]) i++;
  const [a, va] = STOPS[i], [b, vb] = STOPS[i + 1];
  return Math.floor(va + (vb - va) * (t - a) / (b - a) + .5);
};

const run = (frame) => {
  const { W, H, fx, fy } = frame;
  const data = new Uint8ClampedArray(W * H * 4);
  for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) {
    const v = gray(W, H, fx, fy, x, y), i = (y * W + x) * 4;
    data[i] = data[i + 1] = data[i + 2] = v;
    data[i + 3] = 255;
  }
  globalThis.document = { createElement: () => ({ set width(_) {}, set height(_) {},
    getContext: () => ({ drawImage() {}, getImageData: () => ({ data }) }) }) };
  const dots = [];
  let put = null;
  const ctx = { save() {}, restore() {}, translate() {}, fillRect() {}, beginPath() {}, fill() {}, arc: (x, y, r) => dots.push([x, y, r]), putImageData: (img) => { put = img; } };
  G.halftone(ctx, { width: W, height: H }, { W, H, mode: frame.mode, pitch: frame.pitch, angle: frame.angle, contrast: frame.contrast, threshold: frame.threshold, ink: '#000000', paper: '#ffffff' });
  return { dots, mask: put ? Array.from({ length: W * H }, (_, i) => (put.data[i * 4] === 0 ? '1' : '0')).join('') : null };
};

const FRAMES = [
  { name: 'small', W: 120, H: 150, fx: .55, fy: .4, pitch: 8, angle: 45, contrast: 1.4, whole: true },
  { name: 'tight', W: 96, H: 64, fx: .5, fy: .34, pitch: 6, angle: 45, contrast: 1.4, whole: true },
  { name: 'axis', W: 96, H: 96, fx: .6, fy: .36, pitch: 8, angle: 30, contrast: 2, whole: true },
  { name: 'circle', W: 600, H: 600, fx: .55, fy: .4, pitch: 8, angle: 45, contrast: 1.4 },
  { name: 'tilt', W: 440, H: 600, fx: .5, fy: .34, pitch: 8, angle: 45, contrast: 1.4 },
  { name: 'cut', W: 680, H: 840, fx: .6, fy: .36, pitch: 8, angle: 45, contrast: 1.4 },
];
const MASKS = [
  { name: 'mask', W: 60, H: 75, fx: .55, fy: .4, mode: 'mask', contrast: 1.4 },
  { name: 'high', W: 40, H: 40, fx: .5, fy: .5, mode: 'mask', contrast: 1, threshold: .7 },
];

const lines = ['// GENERATED by scripts/halftone-goldens.mjs from plakat-gen.js. Do not edit.', '',
  'package io.github.youndie.plakat.agit', '',
  '/** A frame of the halftone over the stand-in, and what the design\'s own function draws on it. */',
  'internal class HalftoneGolden(', '    val w: Int,', '    val h: Int,', '    val fx: Double,', '    val fy: Double,',
  '    val pitch: Double,', '    val angle: Double,', '    val contrast: Double,', '    val count: Int,', '    val sums: List<Double>,',
  '    val at: Map<Int, List<Double>>,', ')', '', 'internal class MaskGolden(', '    val w: Int,', '    val h: Int,', '    val fx: Double,', '    val fy: Double,',
  '    val contrast: Double,', '    val threshold: Double,', '    val bits: String,', ')', '', 'internal object HalftoneGoldens {', '    val frames: List<HalftoneGolden> =', '        listOf('];
const dbl = (v) => (Number.isInteger(v) ? `${v}.0` : `${v}`);
const triple = (d) => `listOf(${d.map(dbl).join(', ')})`;
for (const f of FRAMES) {
  const { dots } = run(f);
  const sums = [0, 1, 2].map((k) => dots.reduce((s, d) => s + d[k], 0));
  const every = f.whole ? 1 : Math.floor(dots.length / 24);
  lines.push('            HalftoneGolden(', `                ${f.W},`, `                ${f.H},`, `                ${dbl(f.fx)},`, `                ${dbl(f.fy)},`,
    `                ${dbl(f.pitch)},`, `                ${dbl(f.angle)},`, `                ${dbl(f.contrast)},`, `                ${dots.length},`,
    `                listOf(${sums.map(dbl).join(', ')}),`, '                mapOf(');
  dots.forEach((d, i) => { if (i % every === 0) lines.push(`                    ${i} to ${triple(d)},`); });
  lines.push('                ),', '            ),');
}
lines.push('        )', '', '    val masks: List<MaskGolden> =', '        listOf(');
for (const m of MASKS) {
  const { mask } = run(m);
  const chunks = mask.match(/.{1,96}/g).map((c, i, all) => `                "${c}"${i < all.length - 1 ? ' +' : ','}`);
  lines.push('            MaskGolden(', `                ${m.W},`, `                ${m.H},`, `                ${dbl(m.fx)},`, `                ${dbl(m.fy)},`, `                ${dbl(m.contrast)},`, `                ${dbl(m.threshold ?? .5)},`,
    chunks[0], ...chunks.slice(1).map((c) => `    ${c}`), '            ),');
}
lines.push('        )', '}', '');

const text = lines.join('\n');
if (process.argv.includes('--check')) {
  let current = '';
  try { current = readFileSync(OUT, 'utf8'); } catch {}
  if (current !== text) {
    console.error(`${OUT} is stale against plakat-gen.js: run node scripts/halftone-goldens.mjs`);
    process.exit(1);
  }
  console.log('halftone goldens are up to date');
} else {
  writeFileSync(OUT, text);
  console.log(`wrote ${OUT}`);
}
